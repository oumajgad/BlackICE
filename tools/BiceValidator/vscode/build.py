"""Build the BlackICE Script extension into tools/BiceValidator/dist/blackice-script.vsix.

    pip install -r ../requirements-build.txt      # PyInstaller and pygls
    python build.py                               # needs Node.js and npm as well

In order:
1. bicevalidator-lsp.exe, the language server, from ../bicevalidator-lsp.spec into server/;
2. the colouring grammar, made from the keyword pages in docs/script, into syntaxes/;
3. the rule list in package.json's `disabledRules` setting, brought in step with rules.py;
4. npm install, the bundled extension.js, and a type check;
5. the tests: the extension started in a fresh copy of VS Code against a small mod
   (skip with --no-test; the first run downloads that copy, about 150 MB);
6. the .vsix, with the server inside it.
"""

import json
import os
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TOOL = os.path.dirname(HERE)
DIST = os.path.join(TOOL, "dist")
VSIX = os.path.join(DIST, "blackice-script.vsix")
SERVER = os.path.join(HERE, "server", "bicevalidator-lsp.exe")

sys.path.insert(0, TOOL)
from bicevalidator import rules, schema  # noqa: E402


def step(text):
    print("\n== %s" % text, flush=True)


def npm(*args):
    npm_cmd = shutil.which("npm") or shutil.which("npm.cmd")
    if npm_cmd is None:
        sys.exit("npm was not found. Install Node.js LTS: winget install OpenJS.NodeJS.LTS")
    subprocess.run([npm_cmd, *args], cwd=HERE, check=True)


def build_server():
    step("language server")
    subprocess.run([sys.executable, "-m", "PyInstaller", "--noconfirm", "--clean",
                    "--distpath", os.path.join(HERE, "server"),
                    "--workpath", os.path.join(TOOL, "build"),
                    os.path.join(TOOL, "bicevalidator-lsp.spec")], cwd=TOOL, check=True)
    print("  %s, %.0f MB" % (SERVER, os.path.getsize(SERVER) / 1048576))


# Keys that shape the files rather than doing anything - coloured as structure.
STRUCTURE = ["country_event", "province_event", "option", "trigger", "mean_time_to_happen",
             "ai_chance", "ai_will_do", "potential", "allow", "effect", "limit", "modifier",
             "diplomatic_decisions", "political_decisions", "economic_decisions",
             "random_list", "random", "and", "or", "not", "id", "title", "desc", "picture",
             "name", "is_triggered_only", "fire_only_once", "major", "factor", "days",
             "months", "years"]


def _words(names):
    return "|".join(sorted({n for n in names}, key=lambda n: (-len(n), n)))


def grammar(pages_dir):
    """The TextMate grammar, its keyword lists taken from the keyword pages."""
    s = schema.Schema(pages_dir)
    structure = set(STRUCTURE)
    scopes = (s.names("scope") | set(schema.GENERIC_SCOPES)) - structure
    conditions = (s.names("trigger") | s.names("combat")) - structure - scopes
    effects = s.names("effect") - structure - scopes - conditions
    both = (s.names("trigger") | s.names("combat")) & s.names("effect") - structure - scopes

    def keys(words, scope):
        # A keyword only as a key - `war = yes` - not as a value, as in `faction = war`.
        return {"match": r"(?i)(?<![\w.\-])(%s)(?=\s*[=<>])" % _words(words),
                "captures": {"1": {"name": scope}}}

    return {
        "$schema": "https://raw.githubusercontent.com/martinring/tmlanguage/master/tmlanguage.json",
        "name": "BlackICE Script",
        "scopeName": "source.blackice-script",
        "comment": "Generated by vscode/build.py from docs/script - do not edit by hand.",
        "patterns": [
            {"name": "comment.line.number-sign.blackice-script", "match": "#.*$"},
            {"name": "string.quoted.double.blackice-script", "begin": "\"", "end": "\""},
            keys(structure, "keyword.control.blackice-script"),
            keys(scopes, "variable.language.scope.blackice-script"),
            keys(both, "support.function.blackice-script"),
            keys(conditions, "support.function.condition.blackice-script"),
            keys(effects, "entity.name.function.effect.blackice-script"),
            {"match": r"(?<![\w.\-])([A-Za-z_][\w.\-]*)(?=\s*[=<>])",
             "captures": {"1": {"name": "variable.other.property.blackice-script"}}},
            {"name": "constant.numeric.date.blackice-script",
             "match": r"(?<![\w.])\d{1,4}\.\d{1,2}\.\d{1,2}(?![\w.])"},
            {"name": "constant.numeric.blackice-script",
             "match": r"(?<![\w.])[-+]?\d+(\.\d+)?(?![\w.])"},
            {"name": "constant.language.boolean.blackice-script",
             "match": r"(?i)(?<![\w.])(yes|no)(?![\w.])"},
            {"name": "constant.other.tag.blackice-script",
             "match": r"(?<![\w.\-])[A-Z][A-Z0-9]{2}(?![\w.\-])"},
            {"name": "keyword.operator.blackice-script", "match": "[=<>]"},
            {"name": "punctuation.section.block.blackice-script", "match": "[{}]"},
        ],
    }


def write_grammar():
    step("grammar")
    pages, source = schema.locate_keyword_pages(os.path.dirname(os.path.dirname(TOOL)))
    path = os.path.join(HERE, "syntaxes", "blackice-script.tmLanguage.json")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        json.dump(grammar(pages), handle, indent=2)
        handle.write("\n")
    print("  from %s" % source)


def rule_setting():
    """(enum, enumDescriptions) for the disabledRules setting, from rules.py."""
    ids = list(rules.RULES)
    return ids, ["%s (%s)" % (r.title.replace("`", ""), r.severity) for r in rules.RULES.values()]


def sync_package_json():
    step("rule list in package.json")
    path = os.path.join(HERE, "package.json")
    with open(path, encoding="utf-8") as handle:
        package = json.load(handle)
    items = package["contributes"]["configuration"]["properties"][
        "blackice.validator.disabledRules"]["items"]
    ids, descriptions = rule_setting()
    if items.get("enum") == ids and items.get("enumDescriptions") == descriptions:
        print("  already in step")
        return
    items["enum"], items["enumDescriptions"] = ids, descriptions
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        json.dump(package, handle, indent=2, ensure_ascii=False)
        handle.write("\n")
    print("  updated: %d rules" % len(ids))


def main():
    build_server()
    write_grammar()
    sync_package_json()
    step("extension")
    npm("install", "--no-audit", "--no-fund")
    npm("run", "compile")
    npm("run", "typecheck")
    if "--no-test" not in sys.argv:
        step("tests in VS Code")
        npm("test")
    step("package")
    os.makedirs(DIST, exist_ok=True)
    npm("run", "package", "--", "-o", VSIX)
    print("\n  %s, %.0f MB" % (VSIX, os.path.getsize(VSIX) / 1048576))
    return 0


if __name__ == "__main__":
    sys.exit(main())
